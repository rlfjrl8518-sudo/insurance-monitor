"""광고 텍스트의 언어를 판별하는 모듈."""

import re

# 한글 음절(가-힣) 포함 여부를 검사하는 정규식
한글_정규식 = re.compile(r"[가-힣]")


def 한국어_포함(텍스트):
    """텍스트에 한글 음절이 하나 이상 포함되어 있으면 True를 반환한다."""
    return bool(한글_정규식.search(텍스트 or ""))


def 외국어_소재인가(광고텍스트):
    """광고 텍스트가 비어있지 않은데 한글이 전혀 없으면(영어/중국어 등 외국어 소재) True를 반환한다."""
    광고텍스트 = (광고텍스트 or "").strip()
    if not 광고텍스트:
        return False
    return not 한국어_포함(광고텍스트)


# 보험설계사/파트너스 모집, 부업 등 채용성 소재를 판별하는 키워드.
# "모집"/"채용" 단독으로는 오탐이 많아(이벤트 참가자 모집, 약관상 "모집종사자" 문구 등)
# 채용 맥락이 명확한 복합 키워드만 사용한다.
채용_소재_정규식 = re.compile(
    r"파트너스|부업|위촉|사관학교|N잡"
    r"|보험설계사.*(채용|모집|도전)"
    r"|설계사\s*(모집|채용)"
    r"|공개채용|1인GA|정착지원금"
)


def 채용_소재인가(광고텍스트):
    """광고 텍스트가 보험설계사/파트너스 모집, 부업 등 채용성 소재이면 True를 반환한다."""
    return bool(채용_소재_정규식.search(광고텍스트 or ""))


# 보험 광고 본문 뒤에 붙는 법정 고지문·심의번호. 본문보다 길 때가 많아 분류를 흐린다.
# '*'로 시작하는 줄 중 고지 성격인 것만 지운다('*암진단비 최대 10회'처럼 보장 설명인 줄은 남긴다).
_고지_키워드 = re.compile(
    r"지급(이|은|이 )?\s*제한|지급\s*여부|면책|해약\s*환급금|해지\s*(시|할)|심의필|준법감시|계약\s*체결\s*전"
    r"|약관|상품\s*설명서|보험료가\s*인상|인수가\s*거절|보장\s*내용이\s*달라|예금자\s*보호|갱신\s*시"
    r"|기준\s*\)"
)
_심의번호 = re.compile(r"(생명|손해)보험협회\s*심의필[^가-힣]*|준법감시인\s*(확인|심의)필[^가-힣]*")


def 고지문_제거(광고텍스트):
    """법정 고지문(*지급한도…, 심의필 제…호)을 걷어낸 본문. 분류 프롬프트에만 쓰고 저장값은 그대로 둔다."""
    조각들 = re.split(r"(?=[*※])", 광고텍스트 or "")
    남길것 = [c for c in 조각들 if not (c[:1] in "*※" and _고지_키워드.search(c))]
    return re.sub(r"\s+", " ", _심의번호.sub(" ", "".join(남길것))).strip()


if __name__ == "__main__":
    원문 = ("2026년 치아보험 추천 10년 동안 동일한 보험료로 치과 치료 대비해요 (무)THE건강한치아보험Ⅴ "
          "*계약 체결 전 상품 설명서 및 약관 참조 *기존 계약 해지 후 신계약 체결 시 보험인수가 거절되거나 "
          "생명보험협회 심의필 제2026-00267호(2026-01-08~2027-01-07)")
    assert 고지문_제거(원문) == "2026년 치아보험 추천 10년 동안 동일한 보험료로 치과 치료 대비해요 (무)THE건강한치아보험Ⅴ", 고지문_제거(원문)
    남김 = "3대 질병 보장 * 암진단비 최대 10회 (부위별 최초 1회한) * 원발암 뿐 아니라 전이암까지 보장"
    assert 고지문_제거(남김) == 남김
    print("ok")
