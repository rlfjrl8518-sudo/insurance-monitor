"""광고주 페이지명 매칭 검증. 다른 회사가 섞이지 않는지가 핵심이다."""

from collections import Counter

from src.scraper import 페이지명_정규화, _근접_후보


def test_공백_유무를_무시한다():
    """이게 DB손해보험이 통째로 0건이 되던 원인이었다."""
    assert 페이지명_정규화("DB손해보험") == 페이지명_정규화("DB 손해보험")
    assert 페이지명_정규화("DB 손해보험") == 페이지명_정규화("DB  손해보험")
    assert 페이지명_정규화("KB손해보험") == 페이지명_정규화("KB 손해보험")
    # NBSP 등 공백 종류가 달라도 같아야 한다
    assert 페이지명_정규화("DB 손해보험") == 페이지명_정규화("DB 손해보험")


def test_다른_회사는_절대_섞이지_않는다():
    """실제 수집 데이터에 함께 존재하는 이름들. 하나라도 붙으면 대시보드가 오염된다."""
    분리되어야_함 = [
        ("DB손해보험", "DB생명 다이렉트"),      # 손보 vs 생보, 다른 법인
        ("한화손보", "한화손보 캐롯"),           # 캐롯손해보험은 별개 법인
        ("한화손보", "한화생명"),
        ("삼성화재", "삼성생명 다이렉트"),
        ("현대해상", "현대해상 다이렉트"),       # 같은 그룹이나 별도 채널로 관리 중
        ("DB손해보험", "DB손해보험다이렉트"),
        ("DB손해보험", "보험다나와 • 보험다모아 • 보험비교사이트"),
        ("삼성화재", "삼성화재 다이렉트 착"),
    ]
    for 등록, 다른이름 in 분리되어야_함:
        assert 페이지명_정규화(등록) != 페이지명_정규화(다른이름), f"{등록} / {다른이름}"


def test_근접후보는_알리기만_하고_수집하지_않는다():
    집계 = Counter({
        "DB손해보험 공식": 12,      # 등록명을 품고 있음 -> 후보
        "DB손해보험다이렉트": 30,    # 등록명을 품고 있음 -> 후보
        "DB생명 다이렉트": 20,       # 등록명을 품지 않음 -> 후보 아님
        "육아 소식": 14,
    })
    후보 = dict(_근접_후보("DB손해보험", 집계))
    assert "DB손해보험 공식" in 후보
    assert "DB손해보험다이렉트" in 후보
    assert "DB생명 다이렉트" not in 후보
    assert "육아 소식" not in 후보


def test_빈_이름은_아무것도_끌어오지_않는다():
    assert _근접_후보("", Counter({"아무거나": 3})) == []
    assert 페이지명_정규화(None) == ""


