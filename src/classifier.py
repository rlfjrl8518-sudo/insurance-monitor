def _분류결과_검증(결과, 설정):
    """분류 결과가 허용 목록에 없는 경우 "기타"로 대체한다."""
    분류기준 = 설정["classification"]
    if 결과.get("소재유형") not in 분류기준["소재유형"]:
        결과["소재유형"] = "기타"
    if 결과.get("보종") not in 분류기준["보종"]:
        결과["보종"] = "기타"
    if 결과.get("소구포인트") not in 분류기준["소구포인트"]:
        결과["소구포인트"] = "기타"
    결과["요약"] = 결과.get("요약", "")
    return 결과


