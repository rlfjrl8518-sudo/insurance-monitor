"""수집한 광고 데이터를 CSV로 저장/병합하고 상태(게재중/종료)를 관리하는 모듈."""

import csv
import os
from datetime import datetime, timedelta, timezone

# 한국 표준시 (UTC+9). GitHub Actions 등 UTC 환경에서도 한국 날짜 기준으로 집계하기 위해 사용.
KST = timezone(timedelta(hours=9))


def 오늘_KST():
    """한국 시간(KST) 기준 오늘 날짜를 반환한다."""
    return datetime.now(KST).date()

# CSV 파일의 컬럼 순서
CSV_컬럼 = [
    "ad_id",          # 메타 라이브러리 ID (예전엔 이미지 경로 해시였다 - migrate_v2.py 참고)
    "광고주", "구분", "페이지ID",
    "이미지파일명", "이미지URL", "영상URL",
    "소재유형", "보종", "소구포인트", "요약", "확신도",
    "광고텍스트", "제목", "CTA", "랜딩URL", "게재형식", "플랫폼", "변형수", "묶음ID",
    "광고시작일", "광고종료일", "광고상세URL",
    "수집일",          # 마지막으로 실제 확인된 날
    "최초발견일", "상태", "운영일수", "미확인횟수",
    # 확장 분류 축. 값이 있으면 Postgres 적재 시 labels(jsonb)로 들어간다.
    "레이아웃", "인물노출", "제품노출", "텍스트밀도", "제작방식", "비주얼스타일",
    "퍼널단계", "오퍼", "긴급성", "보험료표기", "보장금액표기",
]

상태_게재중 = "게재중"
상태_종료 = "종료"
# 예전 상태값. 읽을 때 게재중으로 합친다. '신규'는 상태가 아니라 최초발견일로 보여준다.
_옛_게재_상태 = {"신규", "운영중"}

# 수집률이 온전한 회차에서 이만큼 연속으로 안 보여야 종료로 본다.
# 한 번 안 보였다고 바로 내리면, 20일 동안 종료 523건 중 254건이 다시 살아났다.
종료_판정_횟수 = 3

# 수집 결과에서 그대로 옮겨 담는 컬럼
_수집_컬럼 = ["페이지ID", "이미지파일명", "광고텍스트", "제목", "CTA", "랜딩URL", "게재형식",
           "플랫폼", "변형수", "묶음ID", "광고시작일", "광고상세URL", "영상URL"]


def CSV_읽기(csv_경로):
    """CSV 파일을 읽어 ad_id를 키로 하는 딕셔너리로 반환한다. 파일이 없으면 빈 딕셔너리 반환."""
    if not os.path.exists(csv_경로):
        return {}

    결과 = {}
    with open(csv_경로, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("상태") in _옛_게재_상태:
                row["상태"] = 상태_게재중
            결과[row["ad_id"]] = row
    return 결과


def CSV_쓰기(csv_경로, 전체_데이터):
    """ad_id를 키로 하는 딕셔너리를 CSV 파일로 저장한다."""
    os.makedirs(os.path.dirname(csv_경로), exist_ok=True)

    with open(csv_경로, "w", encoding="utf-8-sig", newline="") as f:
        # extrasaction="ignore": CSV_컬럼 스키마가 바뀐 뒤에도(예: 컬럼명 변경/폐지) 기존
        # 파일에서 읽어온 행에 남아있는 예전 컬럼 키 때문에 전체 쓰기가 실패하지 않도록 한다.
        writer = csv.DictWriter(f, fieldnames=CSV_컬럼, restval="", extrasaction="ignore")
        writer.writeheader()
        for ad_id in sorted(전체_데이터.keys()):
            writer.writerow(전체_데이터[ad_id])


def 운영일수_계산(행, 오늘=None):
    """게재 기간. 종료된 광고는 종료일에서 멈춘다.

    예전엔 종료된 광고도 오늘까지 계속 셌다. 그래서 종료 소재 중앙값이 실제 15일인데
    85일로 찍혔고, '90일 이상 장수 소재'가 실제 98건인데 960건이 됐다.
    """
    if 오늘 is None:
        오늘 = 오늘_KST()
    시작 = 행.get("광고시작일") or 행.get("최초발견일")
    if not 시작:
        return 0
    끝 = 행.get("광고종료일") if 행.get("상태") == 상태_종료 and 행.get("광고종료일") else None
    끝일 = datetime.strptime(끝, "%Y-%m-%d").date() if 끝 else 오늘
    return max((끝일 - datetime.strptime(시작, "%Y-%m-%d").date()).days, 0)


def _임시_주소인가(주소):
    """메타 CDN 주소인지. 서명이 걸려 있어 얼마 지나면 403이 된다."""
    return "fbcdn.net" in (주소 or "")


def 더_오래가는_주소(기존, 새것):
    """보관해 둔 주소가 이미 있으면, 만료될 주소로 덮어쓰지 않는다.

    수집 때마다 이미지를 우리 저장소에 올리고 그 주소를 쓰는데, 업로드가 실패하면
    메타 CDN 주소가 그대로 돌아온다. 저장소가 정지된 이틀 사이 그 폴백이 매 수집마다
    돌면서, 이미 보관해 둔 1,500여 건의 주소가 전부 만료될 주소로 바뀌었다.
    보관본이 있으면 그쪽을 유지한다.
    """
    if not 새것:
        return 기존 or ""
    if _임시_주소인가(새것) and 기존 and not _임시_주소인가(기존):
        return 기존
    return 새것


def _갱신(행, 광고, 광고주, 구분, 오늘_문자열):
    행["광고주"] = 광고주
    행["구분"] = 구분
    행["수집일"] = 오늘_문자열
    행["상태"] = 상태_게재중
    행["광고종료일"] = ""
    행["미확인횟수"] = "0"
    행["이미지URL"] = 더_오래가는_주소(행.get("이미지URL"), 광고.get("이미지URL"))
    for 컬럼 in _수집_컬럼:
        if 광고.get(컬럼):
            행[컬럼] = 광고[컬럼]


def _새_행(광고, 광고주, 구분, 오늘_문자열):
    행 = {컬럼: "" for 컬럼 in CSV_컬럼}
    행.update({"ad_id": 광고["ad_id"], "최초발견일": 오늘_문자열})
    _갱신(행, 광고, 광고주, 구분, 오늘_문자열)
    return 행


def 데이터_병합(전체_데이터, 광고주, 구분, 수집된_광고_목록, 오늘=None, 완전수집=True):
    """광고주 한 곳의 이번 수집 결과를 기존 데이터에 합친다.

    - 이번에 보인 광고: 게재중, 수집일=오늘, 미확인횟수=0
    - 이번에 안 보인 게재중 광고: 완전수집(수집률 100%)일 때만 미확인횟수+1,
      종료_판정_횟수에 닿으면 종료. 종료일은 마지막으로 확인된 날(수집일).
      일부만 읽힌 회차엔 '안 보였다'는 게 근거가 못 되므로 건드리지 않는다.

    반환값: (신규_개수, 유지_개수, 신규종료_개수)
    """
    if 오늘 is None:
        오늘 = 오늘_KST()
    오늘_문자열 = 오늘.strftime("%Y-%m-%d")
    본_id = set()
    신규 = 유지 = 종료 = 0

    for 광고 in 수집된_광고_목록:
        ad_id = 광고["ad_id"]
        본_id.add(ad_id)
        if ad_id in 전체_데이터:
            _갱신(전체_데이터[ad_id], 광고, 광고주, 구분, 오늘_문자열)
            유지 += 1
        else:
            전체_데이터[ad_id] = _새_행(광고, 광고주, 구분, 오늘_문자열)
            신규 += 1

    for ad_id, 행 in 전체_데이터.items():
        if 행.get("광고주") != 광고주:
            continue
        행["구분"] = 구분
        if ad_id not in 본_id and 행.get("상태") != 상태_종료 and 완전수집:
            횟수 = int(행.get("미확인횟수") or 0) + 1
            행["미확인횟수"] = str(횟수)
            if 횟수 >= 종료_판정_횟수:
                행["상태"] = 상태_종료
                행["광고종료일"] = 행.get("수집일") or 오늘_문자열
                종료 += 1
        행["운영일수"] = str(운영일수_계산(행, 오늘))

    return 신규, 유지, 종료


def 단일_광고_추가_또는_갱신(전체_데이터, 광고주, 구분, 광고, 오늘=None):
    """수기 등록 1건. 같은 광고주의 다른 광고는 건드리지 않는다. 반환: (ad_id, 신규_여부)"""
    if 오늘 is None:
        오늘 = 오늘_KST()
    오늘_문자열 = 오늘.strftime("%Y-%m-%d")
    ad_id = 광고["ad_id"]
    신규 = ad_id not in 전체_데이터
    if 신규:
        전체_데이터[ad_id] = _새_행(광고, 광고주, 구분, 오늘_문자열)
    else:
        _갱신(전체_데이터[ad_id], 광고, 광고주, 구분, 오늘_문자열)
    전체_데이터[ad_id]["운영일수"] = str(운영일수_계산(전체_데이터[ad_id], 오늘))
    return ad_id, 신규


